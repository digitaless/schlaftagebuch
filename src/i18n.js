export function translate(language, key, params = {}) {
  const value = translations[language]?.[key] ?? translations.de[key] ?? key;
  return value.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`));
}

export function formatDate(date, language, options = { day: "2-digit", month: "2-digit", year: "numeric" }) {
  return new Intl.DateTimeFormat(language === "de" ? "de-CH" : language, options).format(date);
}

export function formatNumber(value, language, options) {
  return new Intl.NumberFormat(language === "de" ? "de-CH" : language, options).format(value);
}

export function formatDuration(totalMinutes, language) {
  if (!Number.isFinite(totalMinutes) || totalMinutes < 0) return "–";
  const hours = Math.floor(totalMinutes / 60);
  const remainingMinutes = totalMinutes % 60;
  return `${hours} ${translate(language, "time.hours")} ${String(remainingMinutes).padStart(2, "0")} ${translate(language, "time.minutes")}`;
}

export function getTranslationKeys(language) {
  return Object.keys(translations[language] ?? {});
}
